export const DICTS: Record<Locale, Dict> = { en, fa }

export function fmtNum(n: number, l: Locale) {
  return n.toLocaleString(l === 'fa' ? 'fa-IR' : 'en-US')
}

export function fmtMonthYear(iso: string, l: Locale) {
  return new Date(iso).toLocaleDateString(l === 'fa' ? 'fa-IR-u-ca-persian' : 'en-US', { month: 'long', year: 'numeric' })
}

export function fmtAgo(iso: string, l: Locale, now = Date.now()) {
  const d = DICTS[l].ago
  const days = Math.floor((now - new Date(iso).getTime()) / 86400000)
  if (days < 1) return d.today
  if (days < 7) return d.days(fmtNum(days, l))
  if (days < 60) return d.weeks(fmtNum(Math.floor(days / 7), l))
  return d.months(fmtNum(Math.floor(days / 30), l))
}

export function useT() {
  const locale = useStore((s) => s.locale)
  return { t: DICTS[locale], locale, n: (x: number) => fmtNum(x, locale) }
}
